import { fileURLToPath } from 'node:url'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import postcss from 'postcss'

const corePath = fileURLToPath(new URL('./packages/canvas-core/src/index.ts', import.meta.url))
const noCopilotPanel = fileURLToPath(new URL('./src/components/NoAgentPanel.tsx', import.meta.url))
const harnessComposer = fileURLToPath(new URL('./src/state/composer.harness.ts', import.meta.url))
const harnessKeysDialog = fileURLToPath(new URL('./src/components/ApiKeysDialog.harness.tsx', import.meta.url))

const ROOT = '.forge3d-root'
// Modules the DSH shell provides; the bundle must use the shell's copies.
const SHELL_MODULES = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

/**
 * The harness build has no in-app copilot: the harness conversation drives the
 * canvas through its own tools. Swapping the modules (rather than hiding the
 * panel at runtime) keeps tiptap, ProseMirror, marked and dompurify out of the
 * bundle.
 */
function withoutCopilotPanel(): Plugin {
  return {
    name: 'forge3d:without-copilot-panel',
    enforce: 'pre',
    resolveId(id) {
      if (/(^|\/)ChatPanel(\.tsx)?$/.test(id)) return noCopilotPanel
      if (/(^|\/)composer(\.ts)?$/.test(id)) return harnessComposer
      if (/(^|\/)ApiKeysDialog(\.tsx)?$/.test(id)) return harnessKeysDialog
      return null
    },
  }
}

/** Confine every rule to the app's container: the page belongs to the harness. */
function scopeCss(css: string) {
  const scope = (selector: string) => {
    const next = selector
      .replace(/:root|:host\b/g, ROOT)
      .replace(/(^|[\s,>+~(])(html|body)(?![\w-])/g, `$1${ROOT}`)
      .replace(/#app(?![\w-])/g, ROOT)
    return next.startsWith(ROOT) ? next : `${ROOT} ${next}`
  }
  return postcss([{
    postcssPlugin: 'forge3d-scope',
    Rule(rule) {
      if ((rule.parent as any)?.name?.endsWith('keyframes')) return
      rule.selectors = rule.selectors.map(scope)
    },
  }]).process(css, { from: undefined }).css
}

/**
 * Wrap the CommonJS output in the DSH client contract:
 * `window.__ModuleLoader__.load({ id, factory: (require) => exports })`,
 * with the scoped CSS inlined.
 */
function moduleLoaderBundle(): Plugin {
  return {
    name: 'forge3d:module-loader-bundle',
    enforce: 'post',
    generateBundle(_options, bundle) {
      let css = ''
      for (const [name, file] of Object.entries(bundle)) {
        if (file.type === 'asset' && name.endsWith('.css')) {
          css += String(file.source)
          delete bundle[name]
        }
      }
      for (const file of Object.values(bundle)) {
        if (file.type !== 'chunk' || !file.isEntry) continue
        file.code = [
          '/* @forge3d/dsh-plugin client. Generated by `npm run build:plugin`; do not edit. */',
          'window.__ModuleLoader__.load({',
          "  id: '@forge3d/dsh-plugin',",
          '  factory: function (require) {',
          '    var module = { exports: {} };',
          '    var exports = module.exports;',
          `    var __FORGE3D_CSS__ = ${JSON.stringify(scopeCss(css))};`,
          file.code,
          '    return module.exports;',
          '  },',
          '});',
          '',
        ].join('\n')
      }
    },
  }
}

export default defineConfig({
  plugins: [withoutCopilotPanel(), tailwindcss(), react(), moduleLoaderBundle()],
  define: {
    __FORGE3D_EMBED__: 'true',
    'process.env.NODE_ENV': JSON.stringify('production'),
  },
  resolve: { alias: { '@forge3d/canvas-core': corePath } },
  build: {
    outDir: 'dsh-plugin/lib',
    emptyOutDir: false,
    copyPublicDir: false,
    cssCodeSplit: false,
    lib: {
      entry: fileURLToPath(new URL('./src/plugin.tsx', import.meta.url)),
      formats: ['cjs'],
      fileName: () => 'client.js',
    },
    rolldownOptions: {
      external: SHELL_MODULES,
      output: { inlineDynamicImports: true },
    },
  },
})
